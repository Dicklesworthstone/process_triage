//! Select the next pressure-remediation tier from an already checked plan.
//!
//! This module never invents actions or predicts PSI percentages. It ranks the
//! positive, process-attributed pressure-cost reductions already reported by the
//! decision model, then retains only the least disruptive available tier. The
//! caller still rechecks tree safety for that selection and all execution gates.

use crate::decision::Action;
use crate::plan::{ActionConfidence, ActionRouting, Plan, PlanAction};
use pt_common::{IdentityQuality, ProcessIdentity, StartId};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::BTreeMap;

/// Pressure resource whose modeled burden the operator wants to reduce.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReliefGoal {
    All,
    Cpu,
    Memory,
    Io,
}

impl ReliefGoal {
    pub fn canonical(self) -> &'static str {
        match self {
            Self::All => "relieve",
            Self::Cpu => "cpu-pressure",
            Self::Memory => "mem-pressure",
            Self::Io => "io-pressure",
        }
    }

    fn includes(self, resource: &str) -> bool {
        self == Self::All
            || matches!(
                (self, resource),
                (Self::Cpu, "cpu") | (Self::Memory, "memory") | (Self::Io, "io")
            )
    }
}

/// Only one tier is selected in a plan; the others require another assessment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ReliefTier {
    Deprioritize,
    Pause,
    Terminate,
}

impl ReliefTier {
    fn for_action(action: Action) -> Option<Self> {
        match action {
            Action::Renice | Action::Throttle | Action::CapMemory => Some(Self::Deprioritize),
            Action::Pause | Action::Freeze => Some(Self::Pause),
            Action::Kill => Some(Self::Terminate),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ReliefStatus {
    RemediesAvailable,
    NoEligibleRemedies,
    BudgetExhausted,
}

/// One remedy for an exact process incarnation, possibly with a staged pause.
#[derive(Debug, Clone, Serialize)]
pub struct ReliefStep {
    /// Existing ID of the primary remedy; never regenerated by the selector.
    pub action_id: String,
    /// Existing prerequisite/primary IDs in execution order.
    pub action_ids: Vec<String>,
    pub target: ProcessIdentity,
    pub action: Action,
    pub tier: ReliefTier,
    pub modeled_relief: f64,
    pub expected_loss: f64,
    pub rationale: String,
}

/// Unselected remedies are alternatives, not an automatic escalation sequence.
#[derive(Debug, Clone, Serialize)]
pub struct ReliefTierGroup {
    pub tier: ReliefTier,
    pub requires_new_plan: bool,
    pub remedies: Vec<ReliefStep>,
}

#[derive(Debug, Clone, Serialize)]
pub struct ReliefExclusion {
    pub pid: Option<u32>,
    pub start_id: Option<String>,
    pub reason: &'static str,
}

/// A bounded, auditable next step rather than a physical recovery guarantee.
#[derive(Debug, Clone, Serialize)]
pub struct ReliefPlan {
    pub goal: ReliefGoal,
    pub status: ReliefStatus,
    pub unit: &'static str,
    /// The current heuristic cannot establish attainment of a physical target.
    pub goal_achievable: Option<bool>,
    pub selected_tier: Option<ReliefTier>,
    pub remediation_ladder: Vec<ReliefStep>,
    pub alternatives: Vec<ReliefTierGroup>,
    pub selected_action_ids: Vec<String>,
    pub selected_targets: Vec<ProcessIdentity>,
    pub selected_pids: Vec<u32>,
    pub total_modeled_relief: f64,
    pub excluded: Vec<ReliefExclusion>,
    pub assumptions: Vec<&'static str>,
}

/// Select only final, unblocked direct actions with positive observed-model credit.
///
/// `max_actions` counts process remedies, not the preparatory pause attached to a
/// kill. A zero budget never advances to a more disruptive tier. Candidate and
/// plan order do not affect selection. The returned IDs refer to the input plan;
/// callers must retain those exact actions and recheck safety after narrowing it.
pub fn select_relief_plan(
    goal: ReliefGoal,
    candidates: &[Value],
    plan: &Plan,
    max_actions: Option<usize>,
) -> ReliefPlan {
    let mut pid_counts = BTreeMap::new();
    for candidate in candidates {
        if let Some(pid) = candidate_pid(candidate) {
            *pid_counts.entry(pid).or_insert(0_usize) += 1;
        }
    }
    let mut action_id_counts = BTreeMap::new();
    for action in &plan.actions {
        *action_id_counts
            .entry(action.action_id.as_str())
            .or_insert(0_usize) += 1;
    }

    let mut tiers: BTreeMap<ReliefTier, Vec<ReliefStep>> = BTreeMap::new();
    let mut excluded = Vec::new();
    for candidate in candidates {
        let result = candidate_step(goal, candidate, plan, &pid_counts, &action_id_counts);
        match result {
            Ok(step) => tiers.entry(step.tier).or_default().push(step),
            Err(reason) => excluded.push(ReliefExclusion {
                pid: candidate_pid(candidate),
                start_id: candidate["start_id"].as_str().map(str::to_string),
                reason,
            }),
        }
    }
    for steps in tiers.values_mut() {
        steps.sort_by(|a, b| {
            // Both inputs are finite and nonnegative. The denominator keeps
            // zero-loss actions well-defined without claiming a probability.
            let priority = |step: &ReliefStep| step.modeled_relief / (1.0 + step.expected_loss);
            priority(b)
                .total_cmp(&priority(a))
                .then_with(|| a.expected_loss.total_cmp(&b.expected_loss))
                .then_with(|| b.modeled_relief.total_cmp(&a.modeled_relief))
                .then_with(|| a.target.pid.0.cmp(&b.target.pid.0))
                .then_with(|| a.target.start_id.0.cmp(&b.target.start_id.0))
                .then_with(|| a.target.uid.cmp(&b.target.uid))
                .then_with(|| a.action_id.cmp(&b.action_id))
        });
    }

    let selected_tier = tiers.keys().next().copied();
    let budget = max_actions.unwrap_or(usize::MAX);
    let mut remediation_ladder = Vec::new();
    let mut total_modeled_relief = 0.0;
    let mut alternatives = Vec::new();
    for (tier, steps) in tiers {
        let mut remaining = Vec::new();
        for step in steps {
            if Some(tier) == selected_tier && remediation_ladder.len() < budget {
                let next_total = total_modeled_relief + step.modeled_relief;
                if next_total.is_finite() {
                    total_modeled_relief = next_total;
                    remediation_ladder.push(step);
                    continue;
                }
                excluded.push(ReliefExclusion {
                    pid: Some(step.target.pid.0),
                    start_id: Some(step.target.start_id.0.clone()),
                    reason: "modeled_relief_sum_overflow",
                });
            }
            remaining.push(step);
        }
        if !remaining.is_empty() {
            alternatives.push(ReliefTierGroup {
                tier,
                requires_new_plan: true,
                remedies: remaining,
            });
        }
    }
    excluded.sort_by(|a, b| {
        a.pid
            .cmp(&b.pid)
            .then_with(|| a.start_id.cmp(&b.start_id))
            .then_with(|| a.reason.cmp(b.reason))
    });
    let status = if !remediation_ladder.is_empty() {
        ReliefStatus::RemediesAvailable
    } else if selected_tier.is_some() && budget == 0 {
        ReliefStatus::BudgetExhausted
    } else {
        ReliefStatus::NoEligibleRemedies
    };
    ReliefPlan {
        goal,
        status,
        unit: "heuristic_loss_units",
        goal_achievable: None,
        selected_tier: if remediation_ladder.is_empty() {
            None
        } else {
            selected_tier
        },
        selected_action_ids: remediation_ladder
            .iter()
            .flat_map(|step| step.action_ids.iter().cloned())
            .collect(),
        selected_targets: remediation_ladder
            .iter()
            .map(|step| step.target.clone())
            .collect(),
        selected_pids: remediation_ladder
            .iter()
            .map(|step| step.target.pid.0)
            .collect(),
        total_modeled_relief,
        remediation_ladder,
        alternatives,
        excluded,
        assumptions: vec![
            "Relief is a reduction in heuristic pressure-loss units, not a PSI percentage, freed bytes, or measured recovery guarantee.",
            "Only the least disruptive eligible tier is selected; later tiers and budget leftovers require a fresh assessment and plan, never automatic escalation.",
            "Pressure never grants destructive eligibility: a selected kill must already be the evidence-only decision and an executable direct plan action.",
            "Observed attribution covers the exact process, not its parent, agent, cgroup peers, or uniquely reclaimable memory.",
            "Within a tier, remedies are ranked by modeled relief divided by one plus expected loss, with deterministic identity tie-breaks.",
            "Remedy ranking is informational; the saved executable plan retains its child-before-parent and staged-action order.",
            "Recheck the selected process tree, identity, policy, and live safety evidence before execution, then measure the result before replanning.",
        ],
    }
}

fn candidate_pid(candidate: &Value) -> Option<u32> {
    u32::try_from(candidate["pid"].as_u64()?).ok()
}

fn candidate_step(
    goal: ReliefGoal,
    candidate: &Value,
    plan: &Plan,
    pid_counts: &BTreeMap<u32, usize>,
    action_id_counts: &BTreeMap<&str, usize>,
) -> Result<ReliefStep, &'static str> {
    let action: Action = serde_json::from_value(candidate["recommended_action"].clone())
        .map_err(|_| "no_supported_final_action")?;
    let tier = ReliefTier::for_action(action).ok_or("no_supported_final_action")?;
    let pid = candidate_pid(candidate)
        .filter(|pid| *pid > 1)
        .ok_or("invalid_process_identity")?;
    let uid = candidate["uid"]
        .as_u64()
        .and_then(|uid| u32::try_from(uid).ok())
        .ok_or("invalid_process_identity")?;
    let start_id = candidate["start_id"]
        .as_str()
        .ok_or("invalid_process_identity")?;
    if StartId::parse(start_id).is_none()
        || start_id
            .rsplit(':')
            .next()
            .and_then(|id| id.parse::<u32>().ok())
            != Some(pid)
    {
        return Err("invalid_process_identity");
    }
    if pid_counts.get(&pid) != Some(&1) {
        return Err("ambiguous_candidate_identity");
    }
    if !matches!(
        candidate["state"].as_str(),
        Some("R" | "S" | "T" | "t" | "I")
    ) || candidate
        .get("zombie_routing")
        .is_some_and(|route| !route.is_null())
    {
        return Err("unsafe_or_unknown_process_state");
    }
    if candidate["policy_blocked"] == true || candidate["policy"]["allowed"] == false {
        return Err("final_policy_refusal");
    }
    let target_actions: Vec<_> = plan
        .actions
        .iter()
        .filter(|entry| {
            entry.target.pid.0 == pid
                && entry.target.uid == uid
                && entry.target.start_id.0 == start_id
        })
        .collect();
    let mut primary_actions = target_actions
        .iter()
        .copied()
        .filter(|entry| entry.action == action);
    let primary = primary_actions
        .next()
        .ok_or("no_matching_executable_action")?;
    if primary_actions.next().is_some() {
        return Err("ambiguous_plan_action");
    }
    if primary.target.quality != IdentityQuality::Full {
        return Err("incomplete_plan_identity");
    }
    let target: ProcessIdentity = serde_json::from_value(candidate["action_target"].clone())
        .map_err(|_| "invalid_action_target")?;
    if target != primary.target {
        return Err("mismatched_action_target");
    }
    if action == Action::CapMemory {
        let cap = primary
            .memory_cap
            .as_ref()
            .ok_or("missing_memory_cap_binding")?;
        if cap.validate(&primary.target).is_err()
            || serde_json::to_value(cap).ok().as_ref() != Some(&candidate["memory_cap"])
        {
            return Err("invalid_memory_cap_binding");
        }
    }
    let mut ordered_actions = target_actions;
    if ordered_actions.iter().any(|entry| {
        entry.target != primary.target
            || !eligible_plan_action(entry)
            || entry.action_id.is_empty()
            || action_id_counts.get(entry.action_id.as_str()) != Some(&1)
    }) {
        return Err("blocked_routed_or_ambiguous_plan_action");
    }
    ordered_actions.sort_by_key(|entry| entry.stage);
    let valid_sequence = match ordered_actions.as_slice() {
        [single] => single.action == action && single.stage == 0,
        [pause, kill] => {
            action == Action::Kill
                && pause.action == Action::Pause
                && pause.stage == 0
                && kill.action == Action::Kill
                && kill.stage == 1
        }
        _ => false,
    };
    if !valid_sequence {
        return Err("unsupported_or_incomplete_action_sequence");
    }
    let (modeled_relief, expected_loss) = pressure_credit(goal, candidate, action)?;
    Ok(ReliefStep {
        action_id: primary.action_id.clone(),
        action_ids: ordered_actions
            .iter()
            .map(|entry| entry.action_id.clone())
            .collect(),
        target: primary.target.clone(),
        action,
        tier,
        modeled_relief,
        expected_loss,
        rationale: candidate["action_rationale"]
            .as_str()
            .unwrap_or("Final executable recommendation with positive modeled pressure relief")
            .to_string(),
    })
}

fn eligible_plan_action(action: &PlanAction) -> bool {
    !action.blocked
        && action.routing == ActionRouting::Direct
        && action.confidence == ActionConfidence::Normal
        && action.original_zombie_target.is_none()
        && action.d_state_diagnostics.is_none()
        && action.supervisor_restart.is_none()
        && (action.action == Action::CapMemory || action.memory_cap.is_none())
}

fn nonnegative(value: &Value) -> Option<f64> {
    value
        .as_f64()
        .filter(|number| number.is_finite() && *number >= 0.0)
}

fn approximately_equal(left: f64, right: f64) -> bool {
    (left - right).abs() <= 1e-9 * left.abs().max(right.abs()).max(1.0)
}

fn pressure_credit(
    goal: ReliefGoal,
    candidate: &Value,
    action: Action,
) -> Result<(f64, f64), &'static str> {
    let report = &candidate["pressure_decision"];
    if report["enabled"] != true
        || report["applied"] != true
        || report["status"] != "applied"
        || report["scope"] != "process"
        || report["chosen_action"] != candidate["recommended_action"]
    {
        return Err("pressure_model_does_not_support_final_action");
    }
    if action == Action::Kill && report["evidence_only_action"] != "kill" {
        return Err("pressure_cannot_authorize_kill");
    }
    let rows = report["actions"]
        .as_array()
        .ok_or("missing_pressure_costs")?;
    let find_row = |name: &Value| -> Option<&Value> {
        let mut matches = rows.iter().filter(|row| row["action"] == *name);
        let row = matches.next()?;
        matches.next().is_none().then_some(row)
    };
    let keep = find_row(&Value::String("keep".into())).ok_or("missing_pressure_costs")?;
    let chosen = find_row(&report["chosen_action"]).ok_or("missing_pressure_costs")?;
    if chosen["eligible"] != true || chosen.get("excluded_reason").is_some_and(|v| !v.is_null()) {
        return Err("pressure_action_not_eligible");
    }
    let expected_loss = nonnegative(&chosen["adjusted_loss"]).ok_or("invalid_expected_loss")?;
    let mut all_relief = 0.0;
    let mut selected_relief = 0.0;
    let mut keep_total = 0.0;
    let mut chosen_total = 0.0;
    for resource in ["cpu", "memory", "io"] {
        let keep_cost = nonnegative(&keep["pressure_by_resource"][resource])
            .ok_or("invalid_resource_pressure_cost")?;
        let chosen_cost = nonnegative(&chosen["pressure_by_resource"][resource])
            .ok_or("invalid_resource_pressure_cost")?;
        let reduction = keep_cost - chosen_cost;
        if reduction < 0.0 {
            return Err("pressure_action_increases_resource_burden");
        }
        let supported_credit = action == Action::Kill
            || (action == Action::CapMemory && resource == "memory")
            || (action != Action::CapMemory && resource == "cpu");
        if !supported_credit && reduction > 0.0 {
            return Err("unsupported_reversible_resource_credit");
        }
        if reduction > 0.0 {
            let observed = |value: &Value| {
                value
                    .as_f64()
                    .is_some_and(|v| v.is_finite() && v > 0.0 && v <= 1.0)
            };
            if !observed(&report["severity"][resource]) || !observed(&report["shares"][resource]) {
                return Err("resource_attribution_unavailable");
            }
        }
        all_relief += reduction;
        keep_total += keep_cost;
        chosen_total += chosen_cost;
        if goal.includes(resource) {
            selected_relief += reduction;
        }
    }
    let reported_relief =
        nonnegative(&report["modeled_pressure_relief"]).ok_or("invalid_modeled_relief")?;
    if reported_relief <= 0.0 {
        return Err("no_positive_modeled_relief");
    }
    let reported_keep = nonnegative(&keep["pressure_cost"]).ok_or("invalid_pressure_cost")?;
    let reported_chosen = nonnegative(&chosen["pressure_cost"]).ok_or("invalid_pressure_cost")?;
    if !all_relief.is_finite()
        || !keep_total.is_finite()
        || !chosen_total.is_finite()
        || !approximately_equal(all_relief, reported_relief)
        || !approximately_equal(keep_total, reported_keep)
        || !approximately_equal(chosen_total, reported_chosen)
    {
        return Err("inconsistent_pressure_costs");
    }
    if !selected_relief.is_finite() || selected_relief <= 0.0 {
        return Err("no_positive_relief_for_requested_resource");
    }
    Ok((selected_relief, expected_loss))
}

